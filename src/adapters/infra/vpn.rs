#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_wg_show_no_peers() {
        let output = "  interface: wg0\n  public key: xTIBA5rboUvnH4htodjb6e697QjLERt1NAB4mZqp8Dg=\n  listening port: 51820\n";
        let status = parse_wg_show_output("wg0", output).unwrap();
        assert_eq!(status.interface, "wg0");
        assert_eq!(status.listen_port, 51820);
        assert!(status.peers.is_empty());
    }

    #[test]
    fn test_parse_wg_show_with_peer() {
        let output = "\
  interface: wg0
  public key: xTIBA5rboUvnH4htodjb6e697QjLERt1NAB4mZqp8Dg=
  listening port: 51820

  peer: PEER_PUB_KEY_HERE_BASE64_44CHARS_PADDING=
    endpoint: 1.2.3.4:51820
    allowed ips: 10.8.0.2/32
    latest handshake: 2 minutes, 5 seconds ago
    transfer: 1.23 KiB received, 456 B sent
";
        let status = parse_wg_show_output("wg0", output).unwrap();
        assert_eq!(status.listen_port, 51820);
        assert_eq!(status.peers.len(), 1);
        let p = &status.peers[0];
        assert_eq!(p.endpoint, Some("1.2.3.4:51820".to_string()));
        assert_eq!(p.allowed_ips, vec!["10.8.0.2/32"]);
        assert!(p.transfer_rx_bytes > 0);
    }

    #[test]
    fn test_parse_transfer_bytes_kib() {
        assert_eq!(parse_transfer_bytes("1.00 KiB received"), 1024);
    }

    #[test]
    fn test_parse_transfer_bytes_mib() {
        assert_eq!(parse_transfer_bytes("1.00 MiB sent"), 1024 * 1024);
    }

    #[test]
    fn test_parse_transfer_bytes_b() {
        assert_eq!(parse_transfer_bytes("456 B sent"), 456);
    }

    #[test]
    fn test_generate_peer_config_format() {
        let adapter = WireGuardAdapter::new();
        let config = adapter.generate_peer_config(
            "laptop",
            "PRIVATE_KEY",
            "10.8.0.2",
            "SERVER_PUB_KEY",
            "vpn.example.com",
            51820,
            Some("1.1.1.1"),
            None,
        );
        assert!(config.contains("[Interface]"));
        assert!(config.contains("[Peer]"));
        assert!(config.contains("10.8.0.2/32"));
        assert!(config.contains("vpn.example.com:51820"));
        assert!(config.contains("DNS = 1.1.1.1"));
        assert!(config.contains("PersistentKeepalive = 25"));
    }

    #[test]
    fn test_generate_peer_config_with_psk() {
        let adapter = WireGuardAdapter::new();
        let config = adapter.generate_peer_config(
            "phone",
            "PRIV",
            "10.8.0.3",
            "PUB",
            "1.2.3.4",
            51820,
            None,
            Some("PRESHARED_KEY"),
        );
        assert!(config.contains("PresharedKey = PRESHARED_KEY"));
    }
}
